def tex_num(x, digits=2):
    """Scientific notation as LaTeX, e.g. 2.4e-02 -> 2.4\\times10^{-2}."""
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    if x == 0:
        return "0"
    e = int(np.floor(np.log10(abs(x))))
    if round(abs(x) / 10 ** e, digits - 1) >= 10:     # 9.97e-5 rounds to 1.0e-4, not 10.0e-5
        e += 1
    if -2 <= e <= 3:
        return f"{x:.{max(0, digits - 1 - e)}f}" if e < digits else f"{x:,.0f}".replace(",", "{,}")
    return f"${x / 10 ** e:.{digits - 1}f}{{\\times}}10^{{{e}}}$"


