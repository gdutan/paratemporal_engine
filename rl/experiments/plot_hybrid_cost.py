# Crossover: sigma* = sqrt(best efficiency / exact work). Exact is cheaper for any target std below sigma*.
rows = []
for p in PROBS:
    d = G[(G.problem == p) & (G.status == "ok")]
    E = d.pivot(index="n", columns="method", values="efficiency_var_x_work")
    W = d.pivot(index="n", columns="method", values="mean_work")
    V = d.pivot(index="n", columns="method", values="mean_variance")
    sampled = [m for m in E.columns if not m.startswith("exhaustive")]
    for n in E.index:
        best_m = E.loc[n, sampled].idxmin()
        eff = E.loc[n, best_m]
        var1 = V.loc[n, "rollouts N=9"] * 9
        c_roll = W.loc[n, "rollouts N=9"] / 9
        rm = Rm[(Rm.problem == p) & (Rm.n == n)].iloc[0]
        row = dict(problem=p, n=n, best_sampled=best_m, best_efficiency=eff, rollout_sd=np.sqrt(var1),
                   rollout_work=c_roll, rho=eff / E.loc[n, "rollouts N=9"],
                   reachable=rm.reachable_live_states, sum_cost_reachable=rm.sum_cost_over_reachable)
        for tag, m in [("std", "exhaustive + merge"), ("lagfree", "exhaustive + merge (lag-free key)"),
                       ("nomerge", "exhaustive no merge")]:
            w = W.loc[n, m] if m in W.columns and not np.isnan(W.loc[n, m]) else np.nan
            row[f"exact_work_{tag}"] = w
            row[f"sigma_star_{tag}"] = np.sqrt(eff / w) if w == w else np.nan
            row[f"rollouts_equiv_{tag}"] = w * var1 / eff if w == w else np.nan
        # Rule of thumb (structural, no sampling): once the live set has saturated, exact merged work per step is at
        # most sum over the reachable set R of (1 + b(s)), and a rollout costs about 2 departures per step, so exact
        # wins once more than N_rule = sum_R (1 + b) / 2 rollouts would be needed, i.e. below
        # sigma_rule = sd(one rollout) / sqrt(N_rule). It ignores the gain rho of better samplers (rho < 1 raises
        # the true crossover) and the slack of the bound before saturation, so it is conservative.
        R_full = Rm[Rm.problem == p].sort_values("n").iloc[-1].sum_cost_over_reachable
        row["rule_rollouts"] = R_full / 2
        row["rule_sigma_star"] = np.sqrt(var1) / np.sqrt(R_full / 2)
        rows.append(row)
X = pd.DataFrame(rows)
